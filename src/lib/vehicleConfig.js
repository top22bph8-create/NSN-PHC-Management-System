export const MISSION_OTHER_PREFIX = 'ภารกิจอื่น ๆ';
export const DEFAULT_MISSION_TYPES = Object.entries(DEFAULT_MISSION_GROUPS)
  .flatMap(([group, items]) => items.map((label) => ({ label, group, active: true })))
  .map((m, i) => ({ id: `m${i + 1}`, ...m }));

// รายการภารกิจที่เคยบันทึกไว้ในตั้งค่า "ก่อนมีหมวด" (ไม่มี version) ใช้ร่วมกับหมวดใหม่ไม่ได้ จึงใช้รายการมาตรฐานใหม่แทน
export function normalizeMissionDoc(data) {
  if (data && Array.isArray(data.list) && data.version === MISSION_LIST_VERSION) return data.list;
  return DEFAULT_MISSION_TYPES;
}
// ใช้จัดกลุ่มช้อยที่ติ๊กในฟอร์ม: คืน [{ name, items:[label] }] เฉพาะที่เปิดใช้งาน
export function groupMissions(list) {
  const map = new Map();
  (list || []).filter((m) => m.active !== false).forEach((m) => {
    const g = m.group || 'อื่น ๆ';
    if (!map.has(g)) map.set(g, []);
    map.get(g).push(m.label);
  });
  return [...map.entries()].map(([name, items]) => ({ name, items }));
}
// ข้อความภารกิจเรียงเป็นข้อๆ: ถ้าติ๊ก "ภารกิจอื่น ๆ" และกรอกรายละเอียดไว้ ให้แสดงรายละเอียดแทนข้อความช้อย
export const missionLines = (v) => asList(v.missionType).map((m) => (m.startsWith(MISSION_OTHER_PREFIX) && v.missionOther ? `${MISSION_OTHER_PREFIX}: ${v.missionOther}` : m));

export async function getMissionTypes() {
  const s = await getDoc(doc(db, 'settings', 'vehicleMissionTypes'));
  return normalizeMissionDoc(s.exists() ? s.data() : null);
}

